def tbl(head, rows):
    h = '<tr>' + ''.join(f'<th>{x}</th>' for x in head) + '</tr>'
    b = ''.join('<tr>' + ''.join(f'<td>{x}</td>' for x in r) + '</tr>' for r in rows)
    return f'<div class="tablewrap"><table>{h}{b}</table></div>'
def P(*xs): return ''.join(f'<p>{x}</p>' for x in xs)
def UL(*xs): return '<ul>' + ''.join(f'<li>{x}</li>' for x in xs) + '</ul>'
def QA(*qa): return ''.join(f'<h3>{q}</h3><p>{a}</p>' for q, a in qa)
def REL(*links): return '<h2>함께 읽으면 좋은 글</h2>' + UL(*[f'<a href="/posts/{s}.html">{t}</a>' for s, t in links])

